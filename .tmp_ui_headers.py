"""给拆出来的 7 个前端文件各加一段抬头。

抬头是作者性的（我写的），"放到文件最前面"是机械的一步，所以用脚本做；
文件内容一个字符都不动。
"""

HEADERS = {
    "core.js": """// 基础知识：状态、转义、点击反馈、悬浮提示。
//
// **必须是第一个加载的**：后面的页面模块都直接用 `S`（全局状态）和 `esc` 这类工具。
// 经典脚本按 <script> 顺序求值：函数声明会提升，`const` 不会——所以放前面。
""",
    "shell.js": """// 外壳那一圈：右侧诊断栏、四角信息卡策略、底部活动带、顶部项目切换器、项目列表。
//
// 这些是"任何页面都在场"的东西，所以跟具体某一页分开放——它们是壳，不是页。
""",
    "projects.js": """// 项目那一摊：选中之后的概览、卡片下方的小字、变更卡、项目检查、
// 启动（卡片会留下）、一条龙流水线、清理。
//
// 它们是"这个项目现在怎么样、下一步做什么"的答案，所以放在一起。
""",
    "notes.js": """// 笔记那一页：项目卡片（只读那一套）、记录与笔记、打开方式、新建项目。
//
// 笔记页复用了主页的项目卡片，但**不加载检查与运行组件**——看记录的时候
// 不该顺带去扫项目。
""",
    "events.js": """// 事件与视图切换：页面之间怎么切、后端推来的事件怎么分发、底部状态栏、
// 详细区（平时不取，点开先摆上次的再刷新）。
//
// 放在页面模块之后：它要把各页的渲染函数接起来。
""",
    "editor.js": """// 编辑器那一摊：工作副本、多文件标签、查找与跳行、配对括号、重排缩进、语法高亮。
//
// 规则（写在文件头，因为它决定了这里的每个函数怎么写）：
// **改动留在输入框里，点「应用」才写文件**；应用前自动留一份快照，能回滚。
""",
    "graph.js": """// 图谱那一页：这一页只做一件事——**把内核里的关系画出来**。
//
// 数据全部来自内核（`graph_stats` / `graph_dump` / `graph_index`），
// 前端不做任何推断。画布用 canvas：一次 path 画完所有边，这是它比 DOM 快的根本原因。
""",
}

for name, header in HEADERS.items():
    path = f"ui/{name}"
    body = open(path, encoding="utf-8").read()
    if body.startswith("// 基础知识") or body.startswith("// 外壳那一圈"):
        print(f"{name}: 已有抬头，跳过")
        continue
    open(path, "w", encoding="utf-8", newline="\n").write(header + body)
    print(f"{name}: 抬头已加（{header.count(chr(10))} 行）")
